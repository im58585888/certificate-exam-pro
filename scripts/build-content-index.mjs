// Generates content/<exam>/index.ts that statically imports every question file, so new batch files are picked up automatically.
import { readdirSync, writeFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../content/", import.meta.url));
for (const exam of readdirSync(root).filter((d) => statSync(root + d).isDirectory())) {
  const files = readdirSync(root + exam).filter((f) => f.endsWith(".json")).sort();
  const names = files.map((f, i) => `q${i}`);
  writeFileSync(
    `${root}${exam}/index.ts`,
    `// Generated by scripts/build-content-index.mjs. Do not edit.\n${files.map((f, i) => `import ${names[i]} from "./${f}";`).join("\n")}\n\nexport default [${names.map((n) => `...${n}`).join(", ")}];\n`,
  );
  console.log(`${exam}: indexed ${files.length} files`);
}
